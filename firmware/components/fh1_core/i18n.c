static bool s_pt_on = true;

void fh1_i18n_init(void)
{
    char lang[4];
    fh1_settings_get_str("ui", "lang", lang, sizeof(lang));
    s_pt_on = strcmp(lang, "en") != 0;
}

const char *fh1_lang(void) { return s_pt_on ? "pt" : "en"; }

void fh1_set_lang(const char *lang)
{
    s_pt_on = strcmp(lang, "en") != 0;
    fh1_settings_set_str("ui", "lang", s_pt_on ? "pt" : "en");
}

const char *fh1_tr(const char *en)
{
    if (!s_pt_on || !en) return en;
    for (size_t i = 0; i < sizeof(s_pt) / sizeof(s_pt[0]); i++) {
        if (strcmp(s_pt[i].en, en) == 0) return s_pt[i].pt;
    }
    return en;
}
