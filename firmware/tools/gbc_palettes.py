#!/usr/bin/env python3
"""Make gbc_palettes.h: the Game Boy Color boot ROM's colour palettes for original Game Boy games, from
SameBoy's open boot ROM source (BootROMs/cgb_boot.asm, MIT/Expat licence, (c) Lior Halphon).

  python3 -I gbc_palettes.py cgb_boot.asm > components/fh1_gb/gbc_palettes.h

The tables: a title checksum per known Nintendo game (with the title's 4th letter for checksums shared by
two games), the palette combination each uses (sprite palette 0, sprite palette 1, background, as offsets
into one flat list of colours), the colours (15-bit, red in the low bits), and the 12 combinations a player
picks with a button held at power-on. The source is only parsed, never executed.
"""
import re
import sys


def number(expr):
    """A small integer expression from the source: numbers joined by '*' and '-' (e.g. "4 * 4 - 1")."""
    if not re.fullmatch(r"[0-9 *\-]+", expr):
        raise ValueError(f"unexpected expression: {expr!r}")
    total = 0
    for i, term in enumerate(expr.split("-")):
        product = 1
        for factor in term.split("*"):
            product *= int(factor.strip())
        total = product if i == 0 else total - product
    return total


def main():
    src = open(sys.argv[1], encoding="utf-8").read().split("\n")

    def block(start, end):
        a = next(i for i, l in enumerate(src) if l.startswith(start))
        b = next(i for i, l in enumerate(src) if l.startswith(end) and i > a)
        return src[a + 1:b]

    checksums, dup_start = [], None
    for l in block("TitleChecksums:", "ChecksumsEnd:"):
        if l.startswith("FirstChecksumWithDuplicate"):
            dup_start = len(checksums)
        m = re.match(r"\s*db \$([0-9A-F]{2})\b", l)
        if m:
            checksums.append(int(m.group(1), 16))
    per = [int(m.group(1)) for l in block("PalettePerChecksum:", "Dups4thLetterArray:")
           for m in [re.match(r"\s*palette_index\s+(\d+)", l)] if m]
    dups = None
    for l in block("Dups4thLetterArray:", "PaletteCombinations:"):
        m = re.match(r'\s*db "([A-Z0-9 &\-]*)"\s*$', l)
        if m:
            dups = m.group(1)
    combos = []
    for l in block("PaletteCombinations:", "Palettes:"):
        m = re.match(r"\s*(raw_)?palette_comb\s+([0-9 ,*\-]+?)\s*(;|$)", l)
        if m:
            vals = [number(v) for v in m.group(2).split(",")]
            combos.append(tuple(v if m.group(1) else v * 4 for v in vals))     # offsets in colours
    colours = []
    for l in block("Palettes:", "KeyCombinationPalettes:"):
        colours += [int(v, 16) for v in re.findall(r"\$([0-9A-F]{4})\b", l)]
    keys = [int(m.group(1)) for l in block("KeyCombinationPalettes:", "TrademarkSymbol:")
            for m in [re.match(r"\s*palette_comb_id\s+(\d+)", l)] if m][:12]
    assert len(checksums) == len(per) and dup_start is not None and dups and len(dups) >= len(checksums) - dup_start
    assert len(keys) == 12 and all(max(c) + 4 <= len(colours) for c in combos)

    o = ["// Game Boy Color palettes for original Game Boy games. Generated by tools/gbc_palettes.py from",
         "// SameBoy's boot ROM source (BootROMs/cgb_boot.asm), MIT/Expat licence, Copyright (c) 2015-2026 Lior Halphon.",
         "#pragma once", "#include <stdint.h>", "",
         f"#define GBC_DUP_START {dup_start}   // from here on, a checksum also needs the title's 4th letter",
         f"static const uint8_t gbc_title_checksums[{len(checksums)}] = {{",
         "    " + ", ".join(f"0x{c:02X}" for c in checksums), "};",
         f'static const char gbc_dup_letters[] = "{dups}";',
         f"static const uint8_t gbc_combo_per_checksum[{len(per)}] = {{", "    " + ", ".join(str(p) for p in per), "};",
         "// Per combination: where sprite palette 0, sprite palette 1 and the background start in gbc_colours.",
         f"static const uint8_t gbc_combos[{len(combos)}][3] = {{",
         "    " + ", ".join("{%d, %d, %d}" % c for c in combos), "};",
         "// 15-bit colours: red in bits 0-4, green 5-9, blue 10-14.",
         f"static const uint16_t gbc_colours[{len(colours)}] = {{"]
    for i in range(0, len(colours), 8):
        o.append("    " + ", ".join(f"0x{c:04X}" for c in colours[i:i + 8]) + ",")
    o += ["};",
          "// The combinations picked by holding a button at power-on: Right, Left, Up, Down, then with A, then with B.",
          f"static const uint8_t gbc_key_combos[12] = {{ {', '.join(str(k) for k in keys)} }};"]
    print("\n".join(o))


if __name__ == "__main__":
    main()
