#!/usr/bin/env python3
"""Turn an 8x8 .hex bitmap font (unifont format, e.g. unscii-8.hex) into an LVGL 9 font in C.

  hexfont.py unscii-8.hex fh1_font_8 > fh1_font8.c

Covers ASCII (0x20-0x7E) and Latin-1 (0xA0-0xFF), so Portuguese accents render. Every glyph is the full
8 x 8 cell, 1 bit per pixel (the space and the middle dot advance only 4 pixels); the line is 9 pixels high with one blank row on top.
Source font: unscii by Viznut (http://viznut.fi/unscii/), public domain.
"""
import sys

RANGES = [(0x20, 0x7E), (0xA0, 0xFF)]
# Narrower than the 8-pixel cell: the space and the middle dot (a full cell each made "a · b" look spaced
# out). Code point: (advance in pixels, glyph offset in pixels).
NARROW = {0x20: (4, 0), 0xB7: (4, -2)}


def main():
    path, name = sys.argv[1], sys.argv[2]
    glyphs = {}
    for line in open(path):
        code, _, bits = line.strip().partition(":")
        if len(bits) == 16:                     # 8x8 cells only
            glyphs[int(code, 16)] = bytes.fromhex(bits)
    out = [f"// {name}: unscii-8 (Viznut, public domain) for LVGL 9, ASCII + Latin-1. Generated by tools/hexfont.py.",
           '#include "lvgl.h"', "", "extern const lv_font_t fh1_sym_8;", "",
           "static const uint8_t glyph_bitmap[] = {"]
    dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},  /* id 0 reserved */"]
    index = 0
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            g = glyphs.get(cp, bytes(8))
            out.append(f"    /* U+{cp:04X} */ " + ", ".join(f"0x{b:02x}" for b in g) + ",")
            adv, ofs = NARROW.get(cp, (8, 0))
            dsc.append(f"    {{.bitmap_index = {index}, .adv_w = {adv * 16}, .box_w = 8, .box_h = 8, .ofs_x = {ofs}, .ofs_y = -1}},")
            index += 8
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    out += dsc
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    gid = 1
    for lo, hi in RANGES:
        out.append(f"    {{.range_start = {lo}, .range_length = {hi - lo + 1}, .glyph_id_start = {gid}, .unicode_list = NULL,"
                   f" .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},")
        gid += hi - lo + 1
    out.append("};")
    out.append(f"""
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = {len(RANGES)},
    .bpp = 1,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = 9,
    .base_line = 1,
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0,
    .underline_thickness = 0,
    .static_bitmap = 1,
    .dsc = &font_dsc,
    .fallback = &fh1_sym_8,           // the FH1's symbols (fh1_sym8.c)
    .user_data = NULL,
}};""")
    out.append('''
// Raw 8 x 8 glyph rows (MSB = leftmost pixel), for drawing before LVGL runs (the boot screen).
const uint8_t *fh1_font8_glyph(uint32_t cp)
{
    if (cp >= 0x20 && cp <= 0x7E) return &glyph_bitmap[(cp - 0x20) * 8];
    if (cp >= 0xA0 && cp <= 0xFF) return &glyph_bitmap[(95 + cp - 0xA0) * 8];
    return &glyph_bitmap[0];
}''')
    print("\n".join(out))


if __name__ == "__main__":
    main()
